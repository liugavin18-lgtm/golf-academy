PAR = [4, 4, 3, 5, 4, 4, 3, 4, 5, 4, 3, 4, 5, 4, 4, 3, 4, 5]
SI = [7, 1, 15, 3, 11, 5, 17, 9, 13, 8, 16, 2, 4, 12, 6, 18, 10, 14]


def strokes_received(hcp, si):
    base, extra = divmod(max(hcp, 0), 18)
    return base + (1 if si <= extra else 0)


def tbl(rows, head):
    return "<table><tr>" + "".join(f"<th>{h}</th>" for h in head) + "</tr>" + "".join("<tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>" for r in rows) + "</table>"


def vs_par(d):
    return {-3: "信天翁", -2: "老鹰", -1: "小鸟", 0: "标准杆", 1: "柏忌", 2: "双柏忌"}.get(d, f"+{d}" if d > 0 else str(d))


# ---- 示例 1/2：同一张卡，比杆赛与积分制
HCP = 21
G = [5, 5, 4, 6, 5, 5, 4, 5, 6, 5, 4, 5, 6, 5, 5, 4, 5, 6]
rows, tg, tn, tp = [], 0, 0, 0
for i in range(18):
    r = strokes_received(HCP, SI[i]); n = G[i] - r; d = n - PAR[i]; pts = max(0, 2 - d)
    tg += G[i]; tn += n; tp += pts
    rows.append((i + 1, PAR[i], SI[i], r, G[i], n, vs_par(d), pts))
CARD = tbl(rows, ["洞", "Par", "SI", "让杆", "总杆", "净杆", "净成绩", "积分"])
EX_STROKE = f"""<p>球手 A：<b>球场差点 {HCP}</b>（= 18 + 3，每洞让 1 杆，另外 SI 1、2、3 的洞再让 1 杆）。下面是她的一张完整记分卡：</p>{CARD}
<p><b>总杆 {tg}</b>　让杆 {HCP}　<b>净杆 {tn}</b>（= {tg} − {HCP}），相对标准杆 72 为 <b>{tn - 72:+d}</b>。</p>
<h3>怎么对照着自己算</h3><ol><li>先数你的让杆数在<b>哪些洞</b>加杆（看 SI）；</li><li>每洞：总杆 − 让杆 = 净杆；</li><li>把 18 洞净杆相加。</li></ol>
<p>注意：第 2 洞 SI = 1，让杆数是 {strokes_received(HCP, 1)}（差点 21 = 18 + 3），所以<b>总杆 5 的柏忌，净杆只有 3</b>（净小鸟）。</p>"""
EX_STAB = f"""<p>用<b>同一张卡</b>（球场差点 {HCP}），换成积分制：每洞<b>净杆</b>换算——净 Par 2 分、净小鸟 3 分、净柏忌 1 分、净双柏忌 0 分。</p>{CARD}
<p>全场<b>积分 {tp} 分</b>。参考：<b>36 分</b>大致相当于打出了和差点一样的成绩，所以这张卡比差点好 {tp - 36} 分。</p>
<h3>积分制的几个提醒</h3><ul><li>每个洞<b>最多只拿 0 分</b>，所以打崩的洞不要硬打，捡球省时间；</li><li>很多比赛用 <b>95%</b> 的差点计算积分（见差点课），具体看赛事细则；</li><li>积分平局用<b>倒数成绩</b>（后 9 洞、后 6 洞……）决胜。</li></ul>"""

# ---- 示例 3：比洞赛（A 差点 12，B 差点 20，B 在 SI1–8 的洞得 1 杆）
A = [5, 5, 3, 6, 4, 5, 4, 5, 5, 4, 3, 5, 5, 4, 5, 3, 5, 6]
B = [6, 6, 4, 7, 5, 6, 4, 6, 6, 5, 4, 5, 6, 5, 5, 4, 5, 6]
diff = 20 - 12
lead = 0; mrows = []; end = None
for i in range(18):
    bs = strokes_received(diff, SI[i]); bn = B[i] - bs
    if A[i] < bn: res, lead = "A 赢", lead + 1
    elif A[i] > bn: res, lead = "B 赢", lead - 1
    else: res = "平洞"
    left = 17 - i
    status = "平分" if lead == 0 else (f"A {lead} UP" if lead > 0 else f"B {-lead} UP")
    mrows.append((i + 1, SI[i], A[i], B[i], bs, bn, res, status))
    if abs(lead) > left and end is None:
        end = (i + 1, abs(lead), left, "A" if lead > 0 else "B"); break
MATCH = tbl(mrows, ["洞", "SI", "A 杆", "B 杆", "B 让杆", "B 净杆", "结果", "比分"])
if end:
    n_, ld, lf, who = end
    final = f"<b>{who} 以 {ld} &amp; {lf} 获胜</b>（打完第 {n_} 洞时，领先 {ld} 洞，只剩 {lf} 洞，比赛提前结束）"
else:
    final = f"打满 18 洞，最终<b>{'A' if lead > 0 else 'B'} {abs(lead)} UP</b>" if lead else "打满 18 洞，<b>平局（All Square）</b>"
EX_MATCH = f"""<p>A 球场差点 12，B 球场差点 20，<b>差 8 杆</b>，所以 B 在难度指数 <b>SI 1–8</b> 的洞各得 1 杆。比洞赛比的是<b>每洞的净杆</b>。</p>{MATCH}
<p>结果：{final}。</p><h3>读表要点</h3><ul><li>B 在 SI ≤ 8 的洞（表里‘B 让杆’为 1）才让杆；</li><li>平洞时比分不变；</li><li>只要领先洞数<b>大于剩余洞数</b>，比赛就结束（这也是‘3 &amp; 2’叫法的来源）。</li></ul>"""

